"""
Automated workflow and pre-commit hook generators.
"""

from pathlib import Path
import os
import stat


GITHUB_WORKFLOW_TEMPLATE = """# Generated by TokenTally (https://github.com/appu2712/tokentally)
name: AI Token & Budget Gate

on:
  pull_request:
    branches: [ main, master ]
  push:
    branches: [ main, master ]

jobs:
  token-budget-audit:
    runs-on: ubuntu-latest
    steps:
      - uses: actions/checkout@v4

      - name: Set up Python
        uses: actions/setup-python@v5
        with:
          python-version: "3.11"

      - name: Install TokenTally
        run: pip install tokentally

      - name: Profile Git Diff & Enforce Review Budget
        run: |
          tokentally diff origin/${{ github.base_ref || 'main' }} --model gpt-4o

      - name: Enforce Codebase Context Limit
        run: |
          tokentally check . --max-tokens 150000 --max-cost 0.40 --model gpt-4o
"""

PRE_COMMIT_HOOK_SCRIPT = """#!/usr/bin/env sh
# TokenTally pre-commit budget hook
echo "⚡ Checking staged changes against LLM budget..."
tokentally diff --staged --model gpt-4o || {
    echo "❌ TokenTally: Staged diff exceeded recommended token threshold!"
    exit 1
}
"""


def scaffold_github_workflow(target_root: str = ".") -> Path:
    """Generate .github/workflows/tokentally-budget.yml."""
    root = Path(target_root).resolve()
    wf_dir = root / ".github" / "workflows"
    wf_dir.mkdir(parents=True, exist_ok=True)
    out_file = wf_dir / "tokentally-budget.yml"
    out_file.write_text(GITHUB_WORKFLOW_TEMPLATE, encoding="utf-8")
    return out_file


def install_git_precommit_hook(target_root: str = ".") -> Path:
    """Install .git/hooks/pre-commit hook."""
    root = Path(target_root).resolve()
    hook_dir = root / ".git" / "hooks"
    if not hook_dir.is_dir():
        raise NotADirectoryError(f"No .git directory found at {root}")

    hook_file = hook_dir / "pre-commit"
    hook_file.write_text(PRE_COMMIT_HOOK_SCRIPT, encoding="utf-8")

    # Make executable on Unix
    try:
        current_stat = os.stat(hook_file)
        os.chmod(hook_file, current_stat.st_mode | stat.S_IEXEC)
    except Exception:
        pass

    return hook_file
